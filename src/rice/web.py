"""Local HTTP server for the rice web configurator.

The server exposes a small JSON API plus (once Task 2 lands) the static UI
assets under ``src/web``. It binds to loopback only and requires a bearer
token for every mutating or config-reading endpoint. The token is generated by
``run_server`` and handed to the browser in the URL, so no config or personal
data is reachable without it.
"""

from __future__ import annotations

import argparse
import hmac
import json
import secrets
import shutil
import webbrowser
from dataclasses import asdict
from datetime import datetime
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlparse

from .apply import apply_config
from .apps import load_catalog
from .config import load_config, save_config, validate_config
from .outputs import detect_outputs
from .paths import config_path, state_home

WEB_ROOT = Path(__file__).resolve().parents[1] / "web"
CATALOG_PATH = Path(__file__).resolve().parents[2] / "defaults" / "apps.toml"
BACKUP_ROOT = state_home() / "rice" / "web-backups"

# Static assets are served from an explicit allowlist so a crafted request can
# never escape WEB_ROOT through ``..`` segments or percent-encoded traversal.
STATIC_FILES = {
    "": "index.html",
    "index.html": "index.html",
    "app.js": "app.js",
    "style.css": "style.css",
}
STATIC_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
}


class RiceHTTPServer(ThreadingHTTPServer):
    daemon_threads = True

    def __init__(self, address, handler, config_path, token, apply_func=None):
        super().__init__(address, handler)
        self.config_path = Path(config_path)
        self.token = token
        self.apply_func = apply_func or apply_config
        self.backup_root = BACKUP_ROOT


class RiceRequestHandler(BaseHTTPRequestHandler):
    server_version = "rice"

    def log_message(self, format, *args):  # noqa: A002 - silence request logs
        return

    # -- helpers ---------------------------------------------------------

    def _send(self, status, payload, content_type="application/json"):
        if isinstance(payload, (bytes, bytearray)):
            body = bytes(payload)
        elif isinstance(payload, str):
            body = payload.encode("utf-8")
        else:
            body = json.dumps(payload).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _send_json(self, status, payload):
        self._send(status, payload)

    def _send_error(self, status, message):
        self._send_json(status, {"error": message})

    def _authorized(self):
        header = self.headers.get("Authorization", "")
        if not header.startswith("Bearer "):
            return False
        supplied = header[len("Bearer "):].strip()
        return hmac.compare_digest(supplied.encode("utf-8"), self.server.token.encode("utf-8"))

    def _require_auth(self):
        if not self._authorized():
            self._send_error(401, "unauthorized")
            return False
        return True

    def _read_json(self):
        length = int(self.headers.get("Content-Length") or 0)
        raw = self.rfile.read(length) if length else b""
        if not raw:
            raise ValueError("empty body")
        return json.loads(raw.decode("utf-8"))

    def _load(self):
        return load_config(self.server.config_path)

    def _outputs(self):
        # Output detection shells out to kscreen-doctor, which may be absent on
        # non-Plasma hosts; a failed probe just reports no outputs.
        try:
            return [asdict(output) for output in detect_outputs()]
        except Exception:
            return []

    def _catalog(self):
        try:
            return load_catalog(CATALOG_PATH)
        except (OSError, ValueError):
            return None

    # -- routing ---------------------------------------------------------

    def do_GET(self):
        path = urlparse(self.path).path
        if path == "/api/health":
            self._send_json(200, {"status": "ok"})
            return
        if path == "/api/state":
            if not self._require_auth():
                return
            self._handle_state()
            return
        if path == "/api/outputs":
            if not self._require_auth():
                return
            self._send_json(200, self._outputs())
            return
        self._serve_static(path)

    def do_PUT(self):
        if urlparse(self.path).path != "/api/config":
            self._send_error(404, "not found")
            return
        if not self._require_auth():
            return
        try:
            body = self._read_json()
        except (ValueError, UnicodeDecodeError):
            self._send_error(400, "invalid JSON body")
            return
        if not isinstance(body, dict) or "config" not in body:
            self._send_error(400, 'body must be {"config": {...}}')
            return
        config = body["config"]
        if not isinstance(config, dict):
            self._send_error(400, "config must be an object")
            return
        errors = validate_config(config)
        if errors:
            self._send_json(400, {"errors": errors})
            return
        save_config(self.server.config_path, config)
        self._send_json(200, {"status": "ok"})

    def do_POST(self):
        path = urlparse(self.path).path
        handlers = {
            "/api/validate": self._handle_validate,
            "/api/apply": self._handle_apply,
            "/api/backup": self._handle_backup,
            "/api/restore": self._handle_restore,
        }
        handler = handlers.get(path)
        if handler is None:
            self._send_error(404, "not found")
            return
        if not self._require_auth():
            return
        handler()

    # -- endpoints -------------------------------------------------------

    def _handle_state(self):
        try:
            config = self._load()
        except (OSError, ValueError):
            config = None
        self._send_json(200, {
            "config": config,
            "validation": validate_config(config) if config is not None else [],
            "outputs": self._outputs(),
            "catalog": self._catalog(),
        })

    def _handle_validate(self):
        try:
            config = self._load()
        except (OSError, ValueError):
            self._send_error(400, "config could not be loaded")
            return
        self._send_json(200, {"errors": validate_config(config)})

    def _handle_apply(self):
        try:
            config = self._load()
        except (OSError, ValueError):
            self._send_error(400, "config could not be loaded")
            return
        errors = validate_config(config)
        if errors:
            self._send_json(400, {"errors": errors})
            return
        try:
            self.server.apply_func(self.server.config_path, dry_run=False)
        except Exception as exc:  # noqa: BLE001 - surfaced as a clean JSON error
            self._send_error(400, str(exc))
            return
        self._send_json(200, {"status": "ok"})

    def _handle_backup(self):
        try:
            stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
            root = self.server.backup_root
            dest_dir = root / stamp
            suffix = 1
            while dest_dir.exists():
                dest_dir = root / f"{stamp}-{suffix}"
                suffix += 1
            dest_dir.mkdir(parents=True, exist_ok=True)
            dest = dest_dir / "rice.toml"
            shutil.copy2(self.server.config_path, dest)
        except OSError as exc:
            self._send_error(400, f"backup failed: {exc}")
            return
        self._send_json(200, {"path": str(dest)})

    def _handle_restore(self):
        try:
            body = self._read_json()
        except (ValueError, UnicodeDecodeError):
            self._send_error(400, "invalid JSON body")
            return
        if not isinstance(body, dict) or not isinstance(body.get("path"), str):
            self._send_error(400, 'body must be {"path": "..."}')
            return
        requested = Path(body["path"]).expanduser()
        root = self.server.backup_root.resolve()
        try:
            resolved = requested.resolve()
        except OSError:
            resolved = requested
        if not resolved.is_relative_to(root):
            self._send_error(400, "path must be inside the backup root")
            return
        if not resolved.is_file():
            self._send_error(404, "backup not found")
            return
        try:
            config = load_config(resolved)
        except (OSError, ValueError):
            self._send_error(400, "backup could not be loaded")
            return
        errors = validate_config(config)
        if errors:
            self._send_json(400, {"errors": errors})
            return
        save_config(self.server.config_path, config)
        self._send_json(200, {"status": "ok"})

    # -- static ----------------------------------------------------------

    def _serve_static(self, path):
        name = path.lstrip("/")
        filename = STATIC_FILES.get(name)
        if filename is None:
            self._send_error(404, "not found")
            return
        filepath = WEB_ROOT / filename
        if not filepath.is_file():
            self._send_error(404, "not found")
            return
        content_type = STATIC_TYPES.get(filepath.suffix, "application/octet-stream")
        self._send(200, filepath.read_bytes(), content_type)


def make_server(config_path, token, apply_func=None, host="127.0.0.1", port=0):
    return RiceHTTPServer((host, port), RiceRequestHandler, config_path, token, apply_func)


def run_server(open_browser=True):
    """Start the configurator on a random loopback port and block until Ctrl-C."""
    token = secrets.token_urlsafe(32)
    httpd = make_server(config_path(), token)
    url = f"http://127.0.0.1:{httpd.server_port}/?token={token}"
    print(url)
    if open_browser:
        webbrowser.open(url)
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        httpd.server_close()
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(prog="rice-config")
    parser.add_argument(
        "--no-browser", action="store_true", help="do not open a browser"
    )
    args = parser.parse_args()
    raise SystemExit(run_server(open_browser=not args.no_browser))
